/**
 * #7 会话压缩**重设计**（bizbatch3）——自然语料（真实感多轮对话）。
 *
 * 背景（落实 `business-e2e-prereg-addendum.md` §六）：bizbatch2（§12.3）用
 * `bulkFiller`（6 × 8000 字符中性填充）把转录推过小窗口，结果近窗口出现
 * thinking-only 空回复（`pi_driver_empty_reply, stopReason:length`）+ 反复紧急压缩
 * 不收敛（活锁），**0 个会话完成、未取得读数**。
 *
 * 本模块把「巨量填充」换成**真实感多轮对话**：逐条业务口径与交代，每条消息体积适中
 * （数百字符，远小于填充件的 8000 字符），靠多轮自然累积把会话推过压缩阈值；窗口大小
 * 保持与失败批次同量级（12k），从而隔离「语料形态」这一变量。
 *
 * 语料纪律（避免给机械面制造无谓噪声）：
 *   · 只提及**授权集合名**（alpha / beta / contoso-trade / fabrikam-retail）——不提未授权
 *     的近似集合名，避免模型顺手去查而被判越界；
 *   · 需要执行的轮只覆盖**互不相同**的 (collection, window)——同对象同请求重复成功执行
 *     会被判 `meaninglessDuplicates`；
 *   · 中段对话以口径交代 / 边界澄清为主，不请求新的执行，靠自然体量推长转录。
 *
 * 语料只作**上下文体量**与**可恢复性**的载体；机械判据见 `./cases` 与 `./judge`。
 * 体量自检：`./experiments.test.ts` 用 `estimateContextTokens` 钉住本语料（仅用户文本）
 * 的 token 下界，确保叠加助手/工具输出后足以跨过配置窗口的压缩阈值。
 */

